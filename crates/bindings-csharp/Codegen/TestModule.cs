namespace SpacetimeDB.Codegen;

using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;

internal static class TestModule
{
    internal static IncrementalValueProvider<bool> IsTestProject(
        IncrementalGeneratorInitializationContext context
    ) =>
        context
            .AnalyzerConfigOptionsProvider.Combine(context.CompilationProvider)
            .Select(
                (input, _) =>
                {
                    var (options, compilation) = input;
                    return options.GlobalOptions.TryGetValue(
                            "build_property.IsTestProject",
                            out var value
                        )
                        && string.Equals(value, "true", StringComparison.OrdinalIgnoreCase)
                        && Module.UsesSharedContexts(compilation);
                }
            );

    internal static void Register(
        IncrementalGeneratorInitializationContext context,
        IncrementalValueProvider<bool> testProjectProvider
    ) =>
        context.RegisterSourceOutput(
            context.CompilationProvider.Combine(testProjectProvider),
            (ctx, input) =>
            {
                var (compilation, isTestProject) = input;
                if (!isTestProject)
                    return;

                var markerType = compilation.GetTypeByMetadataName(
                    "SpacetimeDB.ModuleDescriptorAttribute"
                );
                if (markerType is null)
                    return;

                var modules = Module
                    .TraverseAssemblies(
                        compilation.SourceModule.ReferencedAssemblySymbols,
                        ctx.CancellationToken
                    )
                    .Select(assembly =>
                        (
                            Assembly: assembly,
                            Descriptor: Module.GetModuleDescriptor(assembly, markerType)
                        )
                    )
                    .Where(module => module.Descriptor is not null)
                    .ToArray();
                if (modules.Length == 0)
                    return;

                // Compiler references include transitive dependencies. A root is a marked
                // assembly that is not reachable from another marked assembly. Traverse
                // their dependencies together so shared graphs are visited only once.
                var dependencies = new HashSet<AssemblyIdentity>(
                    Module
                        .TraverseAssemblies(
                            modules
                                .SelectMany(module => module.Assembly.Modules)
                                .SelectMany(module => module.ReferencedAssemblySymbols),
                            ctx.CancellationToken
                        )
                        .Select(assembly => assembly.Identity)
                );
                var roots = modules
                    .Where(module => !dependencies.Contains(module.Assembly.Identity))
                    .OrderBy(module => module.Assembly.Identity.ToString(), StringComparer.Ordinal)
                    .ToArray();
                if (roots.Length != 1)
                {
                    ctx.ReportDiagnostic(
                        ErrorDescriptor.AmbiguousTestModule.ToDiag(
                            string.Join(", ", roots.Select(root => root.Assembly.Identity))
                        )
                    );
                    return;
                }

                ctx.AddSource(
                    "TestModule.g.cs",
                    $"// <auto-generated />\nglobal using {roots[0].Descriptor!.ContainingNamespace.ToDisplayString()};\n"
                );
            }
        );
}
