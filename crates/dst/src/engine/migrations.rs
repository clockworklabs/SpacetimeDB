/// A fully materialized schema migration interaction.
///
/// `target_schema` is the raw schema handed to engine validation. `schema` is
/// the canonical schema the model should observe after the engine applies an
/// accepted migration. Rejected migrations never advance model state.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Migration {
    target_schema: SchemaPlan,
    schema: SchemaPlan,
    expectation: MigrationExpectation,
}

/// Whether the target schema should be accepted or refused by the engine.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MigrationExpectation {
    Accepted,
    Rejected,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct EngineMigrationConfig {
    pub accepted_weight: u64,
    pub rejected_weight: u64,
    pub max_accepted_rules: usize,
    pub rule_weights: MigrationRuleWeights,
}

