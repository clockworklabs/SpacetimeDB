#[derive(Debug, Clone, Copy)]
struct RuleCtx<'a> {
    schema: &'a SchemaPlan,
    model: &'a Model,
    schema_profile: &'a SchemaProfile,
}

/// A positive case emitted by a migration rule.
#[derive(Debug, Clone, PartialEq, Eq)]
struct AcceptedCase {
    rule: RuleId,
    rewrite: SchemaRewrite,
}

impl AcceptedCase {
    fn new(rule: RuleId, rewrite: SchemaRewrite) -> Self {
        Self { rule, rewrite }
    }
}

/// A rejected case emitted by intentionally violating one accepted rule precondition.
#[derive(Debug, Clone, PartialEq, Eq)]
struct RejectedCase {
    rule: RuleId,
    rewrite: SchemaRewrite,
}

impl RejectedCase {
    fn new(rule: RuleId, rewrite: SchemaRewrite) -> Self {
        Self { rule, rewrite }
    }
}

trait MigrationRule: Sync {
    fn accepted_cases(&self, _rng: &Rng, _ctx: RuleCtx<'_>, _rule: RuleId) -> Vec<AcceptedCase> {
        Vec::new()
    }

    fn invalid_cases(&self, _rng: &Rng, _ctx: RuleCtx<'_>, _rule: RuleId) -> Vec<RejectedCase> {
        Vec::new()
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum AcceptedComposition {
    Capped { max_rules: usize },
}

impl Migration {
    fn accepted(target_schema: SchemaPlan) -> anyhow::Result<Self> {
        let schema = canonical_schema(&target_schema)?;
        Ok(Self {
            target_schema,
            schema,
            expectation: MigrationExpectation::Accepted,
        })
    }

    fn rejected(target_schema: SchemaPlan) -> Self {
        Self {
            schema: target_schema.clone(),
            target_schema,
            expectation: MigrationExpectation::Rejected,
        }
    }

    #[cfg(test)]
    pub(crate) fn from_rewrites(base: &SchemaPlan, rewrites: Vec<SchemaRewrite>) -> anyhow::Result<Self> {
        let mut schema = base.clone();
        for rewrite in &rewrites {
            rewrite.apply_to(&mut schema)?;
        }
        Self::accepted(schema)
    }

    /// Canonical schema visible to the DST model after an accepted migration.
    pub(crate) fn schema(&self) -> &SchemaPlan {
        &self.schema
    }

    /// Raw target schema handed to engine validation and auto-migration.
    pub(crate) fn target_schema(&self) -> &SchemaPlan {
        &self.target_schema
    }

    pub(crate) fn expectation(&self) -> MigrationExpectation {
        self.expectation
    }

    pub(crate) fn choose_accepted(
        rng: &Rng,
        schema: &SchemaPlan,
        model: &Model,
        schema_profile: &SchemaProfile,
        config: &EngineMigrationConfig,
    ) -> Option<Self> {
        let max_rules = 1 + rng.index(config.max_accepted_rules.max(1));
        build_accepted_migration(
            rng,
            RuleCtx {
                schema,
                model,
                schema_profile,
            },
            AcceptedComposition::Capped { max_rules },
            &config.rule_weights.entries(),
        )
    }

    pub(crate) fn choose_rejected(
        rng: &Rng,
        schema: &SchemaPlan,
        model: &Model,
        schema_profile: &SchemaProfile,
        config: &EngineMigrationConfig,
    ) -> Option<Self> {
        build_rejected_migration(
            rng,
            RuleCtx {
                schema,
                model,
                schema_profile,
            },
            config,
            &config.rule_weights.entries(),
        )
    }
}

fn build_accepted_migration(
    rng: &Rng,
    ctx: RuleCtx<'_>,
    mode: AcceptedComposition,
    rule_weights: &[(RuleId, u32)],
) -> Option<Migration> {
    let AcceptedComposition::Capped { max_rules } = mode;
    let max_rules = max_rules.max(1);

    for _ in 0..16 {
        if let Ok(migration) = build_accepted_from_evolving_draft(rng, ctx, max_rules, rule_weights) {
            return Some(migration);
        }
    }

    build_accepted_from_evolving_draft(rng, ctx, 1, rule_weights).ok()
}

fn build_accepted_from_evolving_draft(
    rng: &Rng,
    ctx: RuleCtx<'_>,
    max_rules: usize,
    rule_weights: &[(RuleId, u32)],
) -> anyhow::Result<Migration> {
    let mut draft = ctx.schema.clone();
    let mut applied_any = false;

    for _ in 0..max_rules {
        let draft_ctx = RuleCtx {
            schema: &draft,
            model: ctx.model,
            schema_profile: ctx.schema_profile,
        };
        let Some(case) = pick_accepted_case(rng, draft_ctx, rule_weights) else {
            break;
        };
        let _rule = case.rule;
        case.rewrite.apply_to(&mut draft)?;
        applied_any = true;
    }

    anyhow::ensure!(applied_any, "empty accepted migration batch");
    let final_schema = canonical_schema(&draft)?;
    anyhow::ensure!(final_schema != *ctx.schema, "accepted migration batch was no-op");
    Migration::accepted(draft)
}

#[cfg(test)]
fn build_validated_accepted_batch(ctx: RuleCtx<'_>, cases: Vec<AcceptedCase>) -> anyhow::Result<Migration> {
    anyhow::ensure!(!cases.is_empty(), "empty accepted migration batch");

    let mut draft = ctx.schema.clone();
    for case in &cases {
        case.rewrite.apply_to(&mut draft)?;
    }

    let final_schema = canonical_schema(&draft)?;
    anyhow::ensure!(final_schema != *ctx.schema, "accepted migration batch was no-op");
    Migration::accepted(draft)
}

fn build_rejected_migration(
    rng: &Rng,
    ctx: RuleCtx<'_>,
    config: &EngineMigrationConfig,
    rule_weights: &[(RuleId, u32)],
) -> Option<Migration> {
    for _ in 0..16 {
        let max_rules = rng.index(config.max_accepted_rules.max(1));
        if let Ok(migration) = build_rejected_from_evolving_draft(rng, ctx, max_rules, rule_weights) {
            return Some(migration);
        }
    }

    build_rejected_from_evolving_draft(rng, ctx, 0, rule_weights).ok()
}

fn build_rejected_from_evolving_draft(
    rng: &Rng,
    ctx: RuleCtx<'_>,
    max_accepted_rules: usize,
    rule_weights: &[(RuleId, u32)],
) -> anyhow::Result<Migration> {
    let mut draft = ctx.schema.clone();

    for _ in 0..max_accepted_rules {
        let draft_ctx = RuleCtx {
            schema: &draft,
            model: ctx.model,
            schema_profile: ctx.schema_profile,
        };
        let Some(case) = pick_accepted_case(rng, draft_ctx, rule_weights) else {
            break;
        };
        let _rule = case.rule;
        case.rewrite.apply_to(&mut draft)?;
    }

    let rejected_ctx = RuleCtx {
        schema: &draft,
        model: ctx.model,
        schema_profile: ctx.schema_profile,
    };
    let rejected = pick_rejected_case(rng, rejected_ctx, rule_weights)
        .ok_or_else(|| anyhow::anyhow!("no rejected migration candidates"))?;
    let _rule = rejected.rule;
    rejected.rewrite.apply_unchecked_to(&mut draft)?;
    anyhow::ensure!(draft != *ctx.schema, "rejected migration batch was no-op");
    Ok(Migration::rejected(draft))
}

#[cfg(test)]
fn build_validated_rejected_batch(
    ctx: RuleCtx<'_>,
    accepted: Vec<AcceptedCase>,
    rejected: RejectedCase,
) -> anyhow::Result<Migration> {
    let mut draft = ctx.schema.clone();
    for case in &accepted {
        case.rewrite.apply_to(&mut draft)?;
    }

    rejected.rewrite.apply_unchecked_to(&mut draft)?;
    anyhow::ensure!(draft != *ctx.schema, "rejected migration batch was no-op");
    Ok(Migration::rejected(draft))
}

fn rule_by_id(id: RuleId) -> Option<&'static RuleEntry> {
    migration_rules().iter().find(|entry| entry.id == id)
}

fn pick_accepted_case(rng: &Rng, ctx: RuleCtx<'_>, weights: &[(RuleId, u32)]) -> Option<AcceptedCase> {
    for _ in 0..16 {
        let entry = pick_weighted_rule(rng, weights)?;
        if let Some(case) = pick_candidate(rng, entry.rule.accepted_cases(rng, ctx, entry.id)) {
            return Some(case);
        }
    }

    pick_candidate(rng, accepted_cases_for_weights(rng, ctx, weights))
}

fn pick_rejected_case(rng: &Rng, ctx: RuleCtx<'_>, weights: &[(RuleId, u32)]) -> Option<RejectedCase> {
    // Enumerate first so rules with no invalidation hook do not consume weighted retries.
    pick_candidate(rng, rejected_cases_for_weights(rng, ctx, weights))
}

fn pick_weighted_rule(rng: &Rng, weights: &[(RuleId, u32)]) -> Option<&'static RuleEntry> {
    let total = weights.iter().map(|(_, weight)| *weight).sum::<u32>();
    if total == 0 {
        return None;
    }

    let mut ticket = rng.index(total as usize) as u32;
    for &(id, weight) in weights {
        if ticket < weight {
            return Some(rule_by_id(id).expect("rule weight references unregistered migration rule"));
        }
        ticket -= weight;
    }

    None
}

fn accepted_cases_for_weights(rng: &Rng, ctx: RuleCtx<'_>, weights: &[(RuleId, u32)]) -> Vec<AcceptedCase> {
    weights
        .iter()
        .filter(|(_, weight)| *weight > 0)
        .filter_map(|(id, _)| rule_by_id(*id))
        .flat_map(|entry| entry.rule.accepted_cases(rng, ctx, entry.id))
        .collect()
}

fn rejected_cases_for_weights(rng: &Rng, ctx: RuleCtx<'_>, weights: &[(RuleId, u32)]) -> Vec<RejectedCase> {
    weights
        .iter()
        .filter(|(_, weight)| *weight > 0)
        .filter_map(|(id, _)| rule_by_id(*id))
        .flat_map(|entry| entry.rule.invalid_cases(rng, ctx, entry.id))
        .collect()
}

fn pick_candidate<T>(rng: &Rng, mut candidates: Vec<T>) -> Option<T> {
    let idx = choose_index(rng, candidates.len())?;
    Some(candidates.swap_remove(idx))
}

fn accepted_cases_from_rewrites(rule: RuleId, rewrites: Vec<SchemaRewrite>) -> Vec<AcceptedCase> {
    rewrites
        .into_iter()
        .map(|rewrite| AcceptedCase::new(rule, rewrite))
        .collect()
}

fn rejected_cases_from_rewrites(rule: RuleId, rewrites: Vec<SchemaRewrite>) -> Vec<RejectedCase> {
    rewrites
        .into_iter()
        .map(|rewrite| RejectedCase::new(rule, rewrite))
        .collect()
}

fn table_is_pristine(model: &Model, table: &TablePlan) -> bool {
    model.row_count_by_table_name(&table.name) == 0 && !model.ever_inserted_by_table_name(&table.name)
}

