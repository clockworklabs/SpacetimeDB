/// A deterministic schema edit used while building a migration candidate.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SchemaRewrite {
    AddTable { table: TablePlan },
    RemoveTable { table: String },
    AlterTable { table: String, ops: Vec<TableMigrationOp> },
}

/// Table-local migration operations generated by the DST harness.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TableMigrationOp {
    ChangeAccess,
    AddColumn {
        ty: Type,
    },
    AddIndex {
        columns: Vec<usize>,
        algorithm: IndexAlgorithm,
    },
    RemoveIndex {
        columns: Vec<usize>,
    },
    AddSequence {
        sequence: SequencePlan,
    },
    RemoveSequence {
        column: usize,
    },
    AddUniqueConstraint {
        columns: Vec<usize>,
    },
    RemoveUniqueConstraint {
        columns: Vec<usize>,
    },
    ChangePrimaryKey {
        column: Option<usize>,
    },
    ChangeIndex {
        columns: Vec<usize>,
    },
    ChangeColumnType {
        column: usize,
    },
    ReschemaEventTable,
}

/// Stable identity for migration rules.
