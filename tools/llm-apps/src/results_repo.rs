//! Publishing benchmark output to the results repositories.
//!
//! Each benchmark has a public results repository. A local checkout is found with
//! `--results-repo`, then an environment variable, then next to the SpacetimeDB checkout,
//! and is cloned there when missing. Publishing copies a finished run into the checkout
//! at the same relative path, commits it and pushes.

use crate::paths;
use crate::process::Tools;
use anyhow::{bail, Context, Result};
use std::fs;
use std::path::{Path, PathBuf};

pub struct ResultsRepo {
    /// The repository name under github.com/clockworklabs.
    pub name: &'static str,
    /// The environment variable that overrides the checkout location.
    pub env_var: &'static str,
}

pub const ONESHOT: ResultsRepo = ResultsRepo {
    name: "spacetimedb-llm-oneshot-results",
    env_var: "LLM_ONESHOT_RESULTS_REPO",
};

pub const SEQUENTIAL: ResultsRepo = ResultsRepo {
    name: "spacetimedb-llm-sequential-upgrade-results",
    env_var: "LLM_SEQUENTIAL_UPGRADE_RESULTS_REPO",
};

/// Never published: dependencies, build output, generated bindings, secrets, local paths,
/// and telemetry that contains personal data.
const SKIP: &[&str] = &[
    ".DS_Store",
    ".env",
    ".env.local",
    ".git",
    ".spacetime_token",
    ".vite",
    "app-dir.txt", // local absolute path
    "bin",         // .NET build output
    "build",
    "dist",
    "drizzle",         // regenerated by drizzle-kit
    "module_bindings", // regenerated by spacetime generate
    "node_modules",
    "obj", // .NET build output
    "playwright-report",
    "raw-telemetry.jsonl", // email and account IDs
    "run.log",
    "session-transcript.jsonl", // absolute paths and personal data
    "target",
    "test-results",
];

/// Whether a file or directory with this name is left out of published results.
pub fn is_skipped(name: &str) -> bool {
    SKIP.contains(&name) || name.ends_with(".jsonl.bak")
}

impl ResultsRepo {
    fn url(&self) -> String {
        format!("git@github.com:clockworklabs/{}.git", self.name)
    }

    /// Where the local checkout is, whether or not it exists yet.
    pub fn path(&self, explicit: Option<&Path>) -> PathBuf {
        if let Some(path) = explicit {
            return path.to_path_buf();
        }
        if let Some(path) = std::env::var_os(self.env_var) {
            return PathBuf::from(path);
        }
        paths::repo_root().join("..").join(self.name)
    }

    /// The local checkout, cloned first if it does not exist.
    pub fn checkout(&self, tools: &Tools, explicit: Option<&Path>) -> Result<PathBuf> {
        let repo = self.path(explicit);
        if !repo.exists() {
            println!("Cloning {} into {}", self.url(), repo.display());
            let status = tools.command("git").arg("clone").arg(self.url()).arg(&repo).status()?;
            crate::process::check(status, "git clone")?;
        }
        if !repo.join(".git").exists() {
            bail!("{} exists but is not a git checkout", repo.display());
        }
        Ok(repo)
    }

    /// Copies `source` to `relative` in the checkout, commits and, if `push`, pushes.
    pub fn publish(
        &self,
        tools: &Tools,
        explicit: Option<&Path>,
        source: &Path,
        relative: &Path,
        push: bool,
    ) -> Result<()> {
        let repo = self.checkout(tools, explicit)?;
        if !git(tools, &repo, &["status", "--porcelain"])?.trim().is_empty() {
            bail!(
                "{} has uncommitted changes; commit or discard them first",
                repo.display()
            );
        }
        git(tools, &repo, &["pull", "--ff-only"])?;

        let dest = repo.join(relative);
        if dest.exists() {
            bail!("{} already exists", dest.display());
        }
        copy_tree(source, &dest, &|name| is_skipped(name))?;

        let rel = relative.to_string_lossy().replace('\\', "/");
        git(tools, &repo, &["add", "--", &rel])?;
        git(tools, &repo, &["commit", "-m", &format!("Add {rel}")])?;
        println!("Committed {rel} in {}", repo.display());
        if push {
            git(tools, &repo, &["push"])?;
            println!("Pushed.");
        } else {
            println!("Not pushed (--no-push).");
        }
        Ok(())
    }
}

fn git(tools: &Tools, repo: &Path, args: &[&str]) -> Result<String> {
    let out = tools
        .command("git")
        .current_dir(repo)
        .args(args)
        .output()
        .context("failed to run git")?;
    if !out.status.success() {
        bail!(
            "git {} failed in {}:\n{}",
            args.join(" "),
            repo.display(),
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// Recursively copies `from` to `to`, leaving out every entry whose name `skip` accepts.
pub fn copy_tree(from: &Path, to: &Path, skip: &dyn Fn(&str) -> bool) -> Result<()> {
    fs::create_dir_all(to).with_context(|| format!("failed to create {}", to.display()))?;
    for entry in fs::read_dir(from).with_context(|| format!("failed to read {}", from.display()))? {
        let entry = entry?;
        let name = entry.file_name();
        if skip(&name.to_string_lossy()) {
            continue;
        }
        let (src, dst) = (entry.path(), to.join(&name));
        if entry.file_type()?.is_dir() {
            copy_tree(&src, &dst, skip)?;
        } else {
            fs::copy(&src, &dst).with_context(|| format!("failed to copy {}", src.display()))?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn private_and_regenerable_files_are_skipped() {
        for name in [
            "raw-telemetry.jsonl",
            "session-transcript.jsonl",
            "run.log",
            "app-dir.txt",
            ".env",
            "node_modules",
            "module_bindings",
            ".git",
            "logs-20260101-000000.jsonl.bak",
        ] {
            assert!(is_skipped(name), "{name} should be skipped");
        }
        for name in [
            "metadata.json",
            "cost-summary.json",
            "GRADING_RESULTS.md",
            "src",
            "App.tsx",
        ] {
            assert!(!is_skipped(name), "{name} should be published");
        }
    }
}
