use anyhow::Result;
use clap::Command;

// TODO: use clap_markdown instead of this custom implementation in the future
pub fn generate_cli_docs() -> Result<String> {
    let mut cli = crate::command_with_split_help_overrides()?;
    let usage = generate_markdown(&mut cli, 2, &[])?;

    Ok(format!(
        "\
# SpacetimeDB's cargo ci

## Overview

This document provides an overview of the `cargo ci` command-line tool, and documentation for each of its subcommands and options.

{}
---

This document is auto-generated by running:

```bash
cargo ci self-docs
```",
        usage
    ))
}

fn generate_markdown(cmd: &mut Command, heading_level: usize, path: &[String]) -> Result<String> {
    let mut out = String::new();

    let heading = "#".repeat(heading_level);
    out.push_str(&format!("{} `{}`\n\n", heading, cmd.get_name()));

    let path_parts = path.iter().map(String::as_str).collect::<Vec<_>>();
    if crate::split_command_help_package(&path_parts).is_some() {
        let help = cmd.render_long_help().to_string();
        out.push_str("**Help:**\n```text\n");
        out.push_str(help.trim_end());
        out.push_str("\n```\n\n");
        return Ok(out);
    }

    if let Some(long_about) = cmd.get_long_about() {
        out.push_str(&format!("{}\n\n", long_about));
    }

    out.push_str(&format!("**Usage:**\n```bash\n{}\n```\n\n", cmd.render_usage()));

    let mut options = String::new();
    for arg in cmd.get_arguments() {
        let mut names = arg
            .get_long()
            .map(|l| format!("--{}", l))
            .or_else(|| arg.get_short().map(|s| format!("-{}", s)))
            .unwrap_or_else(|| arg.get_id().to_string());
        if let Some(value_names) = arg.get_value_names().filter(|_| arg.get_action().takes_values()) {
            for value_name in value_names {
                names.push_str(&format!(" <{value_name}>"));
            }
        }
        let help = arg
            .get_long_help()
            .or_else(|| arg.get_help())
            .map(|help| help.to_string())
            .unwrap_or_else(|| {
                eprintln!("Warning: argument `{}` is missing help text", arg.get_id());
                "".to_string()
            });
        if help.is_empty() {
            options.push_str(&format!("- `{names}`:\n"));
        } else {
            options.push_str(&format!(
                "- `{}`: {}\n{}",
                names,
                help,
                if help.lines().count() > 1 { "\n" } else { "" }
            ));
        }
    }

    if !options.is_empty() {
        out.push_str("**Options:**\n\n");
        out.push_str(&options);
        out.push('\n');
    }

    for sub in cmd.get_subcommands_mut() {
        let mut sub_path = path.to_vec();
        sub_path.push(sub.get_name().to_owned());
        out.push_str(&generate_markdown(sub, heading_level + 1, &sub_path)?);
    }

    Ok(out)
}
