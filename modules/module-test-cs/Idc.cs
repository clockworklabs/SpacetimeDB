namespace SpacetimeDB.Modules.ModuleTestCs;

using SpacetimeDB;

// Port of modules/module-test/src/idc.rs. The receiver bindings in Receiver/ are generated;
// the codegen test `test_codegen_csharp_outbox_fixture` keeps them up to date.

[Table(Accessor = "idc_outbox", Public = true, Outbox = typeof(Receiver.Reducers.ReceivePing))]
[Index.BTree(Accessor = "by_tag", Columns = new[] { "tag" })]
public partial struct IdcOutbox
{
    [PrimaryKey]
    [AutoInc]
    public ulong id;
    public string tag;

    [Target]
    public Receiver.Identity target;

    [Param("body")]
    public string message;
}

[Table(Accessor = "idc_noop_outbox", Outbox = typeof(Receiver.Reducers.Noop))]
// Match the index accessor generated by the TypeScript sugar's msgId column.
[Index.BTree(Accessor = "msgId", Columns = new[] { "msg_id" })]
public partial struct IdcNoopOutbox
{
    [PrimaryKey]
    [AutoInc]
    public ulong msg_id;

    [Target]
    public Receiver.Identity target;
}

static partial class Module
{
    [Reducer]
    public static void enqueue_idc(ReducerContext ctx, Receiver.Identity target, string message)
    {
        ctx.Db.idc_outbox.Insert(
            new IdcOutbox
            {
                tag = "example",
                target = target,
                message = message,
            }
        );
        ctx.Db.idc_noop_outbox.Insert(new IdcNoopOutbox { target = target });
    }

    [Reducer]
    [OnResult(typeof(IdcOutbox))]
    public static void on_idc_result(ReducerContext ctx, IdcOutbox row, Result<Unit, string> result)
    {
        if (result is Result<Unit, string>.ErrR(var error))
        {
            Log.Warn($"IDC message {row.id} ({row.tag}) failed: {error}");
        }
    }
}
